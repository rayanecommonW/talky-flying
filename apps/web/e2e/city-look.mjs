/** Visual check: load the Blender city, fly a bit, take FPV and chase-cam screenshots. */
import { chromium } from "playwright";
const OUT = new globalThis.URL("../../../logs/e2e/", import.meta.url).pathname;
const browser = await chromium.launch({ headless: true, args: ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", "--ignore-gpu-blocklist", "--use-angle=metal"] });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 760 }, permissions: ["microphone"] })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && !m.text().includes("GL Driver") && errors.push(m.text().slice(0, 200)));
await page.goto(process.env.WEB_URL ?? "http://localhost:5173");
await page.fill(".callsign-input", "OSPREY-5");
await page.click(".power-on");
await page.waitForSelector(".radio");
const t0 = Date.now();
await page.waitForFunction(() => performance.getEntriesByType("resource").some((r) => r.name.includes("city.glb") && r.responseEnd > 0), null, { timeout: 60000 });
await page.waitForTimeout(6000);
console.log(`city loaded in ~${((Date.now() - t0) / 1000).toFixed(1)}s`);
await page.keyboard.press("h");
const fps = await page.evaluate(() => new Promise((r) => { let n = 0; const s = performance.now(); const f = () => { n++; performance.now() - s < 2000 ? requestAnimationFrame(f) : r(n / 2); }; requestAnimationFrame(f); }));
console.log(`fps (headless): ${fps}`);
await page.screenshot({ path: `${OUT}city-fpv.png` });
await page.keyboard.down("w"); await page.waitForTimeout(2500); await page.keyboard.up("w");
await page.keyboard.down("ArrowRight"); await page.waitForTimeout(700); await page.keyboard.up("ArrowRight");
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}city-fpv-2.png` });
await page.keyboard.press("c");
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}city-chase.png` });
console.log("hud:", (await page.locator(".top-right .small").innerText()), "|", await page.locator(".station").innerText());
console.log("errors:", errors.length ? errors : "none");
await browser.close();
