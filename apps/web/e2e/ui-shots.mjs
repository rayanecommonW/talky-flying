// Screenshots of the start screen, settings and the in-flight HUD. Usage: node e2e/ui-shots.mjs [outDir] [url]
import { chromium } from "playwright";
const out = process.argv[2] ?? "/tmp/shots";
const url = process.argv[3] ?? "http://localhost:5173";
const browser = await chromium.launch({ args: ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", "--use-gl=angle", "--use-angle=swiftshader", "--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("pageerror:", e.message));
await page.goto(url);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/start.png` });
await page.click(".glass-station >> nth=5");
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/start-picked.png` });
await page.click(".start-settings");
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/settings-controls.png` });
await page.click(".settings nav button:has-text('Flight')");
await page.screenshot({ path: `${out}/settings-flight.png` });
await page.click(".settings nav button:has-text('Sound')");
await page.screenshot({ path: `${out}/settings-audio.png` });
await page.click(".settings nav button:has-text('Station voices')");
await page.screenshot({ path: `${out}/settings-voices.png` });
await page.click(".nav-foot .close");
await page.click(".glass-local");
await page.fill(".callsign-input", "KESTREL-4");
await page.click(".power-on");
await page.waitForSelector(".radio", { timeout: 30000 });
await page.waitForFunction(() => performance.getEntriesByType("resource").some((r) => r.name.includes("city.glb") && r.responseEnd > 0), null, { timeout: 60000 });
await page.waitForTimeout(6000);
await page.screenshot({ path: `${out}/hud.png` });
await page.keyboard.press("h");
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/hud-hidden.png` });
console.log("hud:", await page.locator(".top-right").innerText());
await browser.close();
